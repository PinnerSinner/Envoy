"""Generates stand-ins for the code the WPF markup compiler would emit, so the app's C# can be type-checked on Linux,
where the WindowsDesktop SDK is not available.

For every XAML file with an x:Class it writes `{namespace}.{class}.g.cs` containing:
- `// <auto-generated/>` and `public partial class {class} : {WPF base type of the root element}`, so a root element
  that disagrees with the code-behind (`<UserControl>` vs `: Window`) fails to compile (REQ-UIF-13);
- one field per x:Name outside templates, with its x:FieldModifier (default `internal`) (REQ-UIF-16);
- `_ = nameof(Handler);` for every event-handler attribute, including ones inside templates, so a handler missing from
  the class fails with CS0103 (REQ-UIF-15);
- an empty `InitializeComponent()`.

Usage: gen_stubs.py <src dir> <out dir>. Exits 1 on an unsupported root, a duplicate x:Class or a bad x:FieldModifier.
"""
import glob
import os
import re
import sys
import xml.etree.ElementTree as ET

WPF = "http://schemas.microsoft.com/winfx/2006/xaml/presentation"
X = "http://schemas.microsoft.com/winfx/2006/xaml"

# Root element -> the base type the WPF markup compiler gives the generated partial class.
BASE_TYPES = {
    "Window": "System.Windows.Window",
    "UserControl": "System.Windows.Controls.UserControl",
    "Application": "System.Windows.Application",
    "Page": "System.Windows.Controls.Page",
    "ResourceDictionary": "System.Windows.ResourceDictionary",
}

TEMPLATE_TAGS = {"ControlTemplate", "DataTemplate", "ItemsPanelTemplate", "HierarchicalDataTemplate"}

FIELD_MODIFIERS = {"public", "internal", "private", "protected", "protected internal"}

_EVENT_NAMES = frozenset("""
    Click Checked Unchecked Indeterminate Loaded Unloaded Initialized SelectionChanged TextChanged ValueChanged
    PasswordChanged RequestNavigate
    MouseDown MouseUp MouseEnter MouseLeave MouseMove MouseWheel MouseDoubleClick
    MouseLeftButtonDown MouseLeftButtonUp MouseRightButtonDown MouseRightButtonUp
    PreviewMouseDown PreviewMouseUp PreviewMouseMove PreviewMouseWheel PreviewMouseDoubleClick
    PreviewMouseLeftButtonDown PreviewMouseLeftButtonUp PreviewMouseRightButtonDown PreviewMouseRightButtonUp
    KeyDown KeyUp PreviewKeyDown PreviewKeyUp TextInput PreviewTextInput
    GotFocus LostFocus GotKeyboardFocus LostKeyboardFocus PreviewGotKeyboardFocus PreviewLostKeyboardFocus
    SizeChanged IsVisibleChanged IsEnabledChanged DataContextChanged
    Closing Closed Activated Deactivated ContentRendered SourceInitialized StateChanged LocationChanged
    DragStarted DragDelta DragCompleted ScrollChanged Expanded Collapsed Opened
    Drop DragOver DragEnter DragLeave PreviewDrop PreviewDragOver PreviewDragEnter PreviewDragLeave
    DropDownOpened DropDownClosed ContextMenuOpening ContextMenuClosing ToolTipOpening ToolTipClosing
    Startup Exit DispatcherUnhandledException SessionEnding
""".split())

_HANDLER_VALUE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class StubError(Exception):
    """A XAML file the stub generator refuses (the message names the file)."""


def event_names():
    """The event names whose attributes are treated as handler references."""
    return _EVENT_NAMES


def is_event_handler(element_local, attr_name, value):
    """True when the attribute wires an event handler: an un-namespaced attribute whose name (or the part after the
    last '.', for attached events such as ButtonBase.Click) is a known event and whose value is a plain identifier.
    `<EventSetter Handler="X">` also counts. Works with ElementTree ("{uri}local") and expat ("uri local") names."""
    if attr_name.startswith("{") or " " in attr_name or "}" in attr_name:
        return False
    if not _HANDLER_VALUE.match(value or ""):
        return False
    if element_local == "EventSetter" and attr_name == "Handler":
        return True
    return attr_name.rsplit(".", 1)[-1] in _EVENT_NAMES


def split_tag(tag):
    """'{uri}local' -> (uri, local); 'local' -> ('', local)."""
    return tuple(tag[1:].split("}", 1)) if tag.startswith("{") else ("", tag)


def build_stub(path):
    """Returns (namespace, class name, stub source) for a XAML file, or None when it has no x:Class."""
    root = ET.parse(path).getroot()
    cls = root.get(f"{{{X}}}Class")
    if not cls:
        return None
    ns, name = cls.rsplit(".", 1)
    _, root_local = split_tag(root.tag)
    base = BASE_TYPES.get(root_local)
    if base is None:
        raise StubError(f"{path}: unsupported x:Class root <{root_local}>")

    fields, handlers = [], []

    def walk(el, in_template):
        uri, local = split_tag(el.tag)
        if local in TEMPLATE_TAGS:
            in_template = True
        for attr, value in el.attrib.items():
            if is_event_handler(local, attr, value) and value not in handlers:
                handlers.append(value)
        field = el.get(f"{{{X}}}Name")
        if field and not in_template and "." not in local:
            if uri == WPF:
                t = local
            elif uri.startswith("clr-namespace:"):
                t = uri.split(":", 1)[1].split(";")[0] + "." + local
            else:
                t = local
            raw = el.get(f"{{{X}}}FieldModifier")
            modifier = "internal" if raw is None else " ".join(raw.lower().split())
            if modifier not in FIELD_MODIFIERS:
                raise StubError(f"{path}: unsupported x:FieldModifier '{raw}' on {field}")
            fields.append((modifier, t, field))
        for child in el:
            walk(child, in_template)

    walk(root, False)
    lines = [
        "// <auto-generated/>",
        "#nullable enable",
        "#pragma warning disable",
        f"namespace {ns};",
        "using System.Windows; using System.Windows.Controls; using System.Windows.Controls.Primitives; using System.Windows.Media; using System.Windows.Documents; using System.Windows.Shapes;",
        f"public partial class {name} : {base}",
        "{",
    ]
    for modifier, t, n in fields:
        lines.append(f"  {modifier} {t} {n} = null!;")
    lines.append("  public void InitializeComponent() {}")
    lines.append("  // Compile-time check that every handler named in the XAML exists (CS0103 otherwise).")
    lines.append("  private void __XamlEventHandlers()")
    lines.append("  {")
    for h in handlers:
        lines.append(f"    _ = nameof({h});")
    lines.append("  }")
    lines.append("}")
    return ns, name, "\n".join(lines) + "\n"


def generate(src, out):
    """Writes one stub per x:Class XAML under src into out. Returns {full class name: stub path}."""
    os.makedirs(out, exist_ok=True)
    seen = {}
    written = {}
    for path in sorted(glob.glob(os.path.join(src, "**", "*.xaml"), recursive=True)):
        parts = os.path.normpath(path).split(os.sep)
        if "obj" in parts or "bin" in parts:
            continue
        stub = build_stub(path)
        if stub is None:
            continue
        ns, name, source = stub
        full = f"{ns}.{name}"
        if full in seen:
            raise StubError(f"{path}: x:Class {full} is already declared by {seen[full]}")
        seen[full] = path
        target = os.path.join(out, f"{full}.g.cs")
        with open(target, "w", encoding="utf-8") as f:
            f.write(source)
        written[full] = target
    return written


def main(argv):
    if len(argv) != 3:
        print("usage: gen_stubs.py <src dir> <out dir>", file=sys.stderr)
        return 2
    try:
        written = generate(argv[1], argv[2])
    except StubError as e:
        print(e, file=sys.stderr)
        return 1
    for full in written:
        print(full)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
