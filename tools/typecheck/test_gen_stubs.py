"""Tests for gen_stubs.py (REQ-UIF-13..17). Run by typecheck.sh before the stubs are generated."""
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_stubs  # noqa: E402

FIXTURES = os.path.join(HERE, "fixtures", "stubs")


class GenStubsTests(unittest.TestCase):
    def setUp(self):
        self.out = tempfile.mkdtemp(prefix="envoy-stubs-")

    def tearDown(self):
        shutil.rmtree(self.out, ignore_errors=True)

    def generate_ok(self):
        return gen_stubs.generate(os.path.join(FIXTURES, "ok"), self.out)

    def stub(self, full_name):
        self.generate_ok()
        with open(os.path.join(self.out, full_name + ".g.cs"), encoding="utf-8") as f:
            return f.read()

    # ---- MUST (REQ-UIF-13, REQ-UIF-15) ----

    def test_usercontrol_base_class(self):
        self.assertIn("public partial class SampleControl : System.Windows.Controls.UserControl", self.stub("Fixtures.Ui.SampleControl"))
        self.assertIn("public partial class SampleWindow : System.Windows.Window", self.stub("Fixtures.Ui.Windows.SampleWindow"))

    def test_application_gets_generated_main(self):
        text = self.stub("Fixtures.Ui.SampleApp")
        self.assertIn("public partial class SampleApp : System.Windows.Application", text)
        self.assertIn("[System.STAThread] public static void Main() {}", text)
        self.assertNotIn("static void Main()", self.stub("Fixtures.Ui.Windows.SampleWindow"))

    def test_unsupported_root_fails(self):
        with self.assertRaises(gen_stubs.StubError) as ctx:
            gen_stubs.generate(os.path.join(FIXTURES, "weird"), self.out)
        self.assertIn("unsupported x:Class root <Canvas>", str(ctx.exception))
        self.assertIn("Weird.xaml", str(ctx.exception))
        result = subprocess.run([sys.executable, os.path.join(HERE, "gen_stubs.py"), os.path.join(FIXTURES, "weird"), self.out],
                                capture_output=True, text=True)
        self.assertEqual(1, result.returncode)
        self.assertIn("unsupported x:Class root <Canvas>", result.stderr)

    def test_auto_generated_header(self):
        for full in self.generate_ok():
            with open(os.path.join(self.out, full + ".g.cs"), encoding="utf-8") as f:
                self.assertEqual("// <auto-generated/>", f.readline().rstrip("\n"))

    def test_event_handlers_emitted_including_templates(self):
        text = self.stub("Fixtures.Ui.SampleControl")
        for handler in ("OnLoaded", "OnGo", "OnTemplateClick", "OnHover"):
            self.assertIn(f"_ = nameof({handler});", text)
        self.assertEqual(1, text.count("_ = nameof(OnGo);"))
        self.assertIn("_ = nameof(OnInputChanged);", self.stub("Fixtures.Ui.Windows.SampleWindow"))

    def test_attached_event_name(self):
        self.assertIn("_ = nameof(OnAnyButton);", self.stub("Fixtures.Ui.SampleControl"))
        self.assertTrue(gen_stubs.is_event_handler("Grid", "ButtonBase.Click", "OnClick"))
        self.assertTrue(gen_stubs.is_event_handler("Grid", "Mouse.PreviewMouseDown", "OnDown"))

    def test_binding_values_not_treated_as_handlers(self):
        text = self.stub("Fixtures.Ui.SampleControl")
        self.assertNotIn("NotAHandler", text)
        self.assertNotIn("OnNotAnEvent", text)
        self.assertFalse(gen_stubs.is_event_handler("Button", "Click", "{Binding Go}"))
        self.assertFalse(gen_stubs.is_event_handler("Button", "Command", "OnGo"))
        self.assertFalse(gen_stubs.is_event_handler("Button", "{http://example}Click", "OnGo"))
        self.assertFalse(gen_stubs.is_event_handler("Button", "http://example Click", "OnGo"))

    # ---- SHOULD (REQ-UIF-14, REQ-UIF-16) ----

    def test_file_named_by_full_class(self):
        written = self.generate_ok()
        self.assertEqual({"Fixtures.Ui.SampleApp", "Fixtures.Ui.SampleControl", "Fixtures.Ui.Windows.SampleWindow"}, set(written))
        self.assertEqual(sorted(["Fixtures.Ui.SampleApp.g.cs", "Fixtures.Ui.SampleControl.g.cs", "Fixtures.Ui.Windows.SampleWindow.g.cs"]), sorted(os.listdir(self.out)))

    def test_duplicate_class_fails(self):
        with self.assertRaises(gen_stubs.StubError) as ctx:
            gen_stubs.generate(os.path.join(FIXTURES, "dup"), self.out)
        message = str(ctx.exception)
        self.assertIn("Fixtures.Ui.Same", message)
        self.assertIn("Dup1.xaml", message)
        self.assertIn("Dup2.xaml", message)

    def test_field_modifier_public(self):
        text = self.stub("Fixtures.Ui.SampleControl")
        self.assertIn("  public Button PublicButton = null!;", text)
        self.assertIn("  private Button PrivateButton = null!;", text)

    def test_default_field_modifier_internal(self):
        text = self.stub("Fixtures.Ui.SampleControl")
        self.assertIn("  internal StackPanel Root = null!;", text)
        self.assertIn("  internal Fixtures.Controls.Gauge Meter = null!;", text)

    def test_bad_field_modifier_fails(self):
        with self.assertRaises(gen_stubs.StubError) as ctx:
            gen_stubs.generate(os.path.join(FIXTURES, "badmodifier"), self.out)
        self.assertIn("friend", str(ctx.exception))

    def test_template_names_not_fields(self):
        self.assertNotIn("InTemplate", self.stub("Fixtures.Ui.SampleControl"))


if __name__ == "__main__":
    unittest.main()
